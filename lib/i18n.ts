/**
 * UI 문자열 사전. 한국어 / 영어 / 일본어.
 * 사용: const { t } = useMemos(); t("home.title")  /  t("capture.elapsed", { n: 12 })
 */
export type Lang = "ko" | "en" | "ja";
export const LANGS: { id: Lang; label: string; locale: string }[] = [
  { id: "ko", label: "한국어", locale: "ko-KR" },
  { id: "en", label: "English", locale: "en-US" },
  { id: "ja", label: "日本語", locale: "ja-JP" },
];
export const LANG_KEY = "memo-lang";

export function detectLang(): Lang {
  if (typeof window === "undefined") return "ko";
  try {
    const saved = window.localStorage.getItem(LANG_KEY) as Lang | null;
    if (saved && LANGS.some((l) => l.id === saved)) return saved;
  } catch {
    /* ignore */
  }
  const nav = (navigator.language || "ko").toLowerCase();
  if (nav.startsWith("ja")) return "ja";
  if (nav.startsWith("en")) return "en";
  return "ko";
}

export function localeOf(lang: Lang): string {
  return LANGS.find((l) => l.id === lang)?.locale ?? "ko-KR";
}

